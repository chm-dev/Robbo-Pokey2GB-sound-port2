/* Export the POKEY SFX table from the dumped Robbo RAM image to sfx_data.c.
 *
 * Source of truth: sound-port2/build/game-live.bin (live RAM $0E00-$BA80,
 * captured via jsA8E after the loader unpacked the game).
 * Engine (disassembled at $B806/$B84B/$B86C):
 *   trigger: A = pattern 0..14 (bit7 = stop all); voice = min(A,3).
 *   pointer  = $B896 + 32*A; counter = 16.
 *   tick: once every 4 PAL frames (RTCLOK&3==0) each active voice emits
 *   pair [counter*2]=AUDC, [counter*2+1]=AUDF walking DOWN 15..0.
 * We store pairs already flipped into playback order.
 */
"use strict";

const fs = require("node:fs");
const path = require("node:path");

const block = fs.readFileSync(path.join(__dirname, "..", "build", "game-live.bin"));
const BASE = 0x0e00;
const TABLE = 0xb896;
const byte = (a) => block[a - BASE];

let out = `/* sfx_data.c - Robbo POKEY sound patterns, verbatim from the game RAM table
 * at $B896 of xex/robbo.xex (verified byte-identical to sound-port/tests/
 * robbo-fast.xex's game block; SHA-256 of canonical XEX per plan/game_info.md).
 *
 * Generated by tools/export_sfx.js - do not edit by hand.
 * Stored in ENGINE PLAYBACK order (last table pair first).
 * AUDC bits: 7-5 distortion, 4 high-note clock, 3-0 linear volume.
 */
#include "sfx_data.h"

const SfxStep sfx_notes[SFX_NOTE_COUNT][SFX_STEPS] = {
`;

for (let n = 0; n < 15; n++) {
  const p = TABLE + 32 * n;
  out += `  { /* $${p.toString(16)} pattern ${n} */\n`;
  const cells = [];
  for (let k = 15; k >= 0; k--) {
    const c = byte(p + k * 2), f = byte(p + k * 2 + 1);
    cells.push(`{0x${c.toString(16).padStart(2, "0").toUpperCase()},0x${f.toString(16).padStart(2, "0").toUpperCase()}}`);
  }
  out += "    " + cells.join(", ") + "\n  },\n";
}
out += `};
`;

fs.writeFileSync(path.join(__dirname, "..", "src", "sfx_data.c"), out);

// quick human-readable summary
for (let n = 0; n < 15; n++) {
  const p = TABLE + 32 * n;
  const s = [];
  for (let k = 15; k >= 0; k--) {
    const c = byte(p + k * 2), f = byte(p + k * 2 + 1);
    s.push(c === 0 && f === 0 ? "--  " : `${c.toString(16).padStart(2, "0")}:${f.toString(16).padStart(2, "0")}`);
  }
  console.log(`p${String(n).padStart(2)} ${s.join(" ")}`);
}
console.log("wrote src/sfx_data.c");
